// Generates src/ui/icons.rs from lucide-react: every icon the web frontend
// imports, as a rune `Icon` whose elements carry lucide's stroke attributes
// (rune reads stroke attributes per element, lucide sets them on <svg>).
//
//   node tools/gen-icons.mjs [path/to/frontend] [path/to/lucide-react]
//
// The frontend's CSS fills the transport glyphs and an active heart; those get
// a filled twin (`*_FILLED`), stroked and filled as the browser draws them.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const frontend = path.resolve(process.argv[2] ?? path.join(here, "../../frontend"));
const lucide = path.resolve(
  process.argv[3] ?? path.join(frontend, "node_modules/lucide-react"),
);

const files = [];
(function walk(dir) {
  for (const f of fs.readdirSync(dir)) {
    const p = path.join(dir, f);
    if (fs.statSync(p).isDirectory()) walk(p);
    else if (/\.tsx?$/.test(f)) files.push(p);
  }
})(path.join(frontend, "src"));

const names = new Set();
for (const f of files) {
  const src = fs.readFileSync(f, "utf8");
  for (const m of src.matchAll(/import\s*\{([^}]*)\}\s*from\s*"lucide-react"/g)) {
    for (const part of m[1].split(",")) {
      const name = part.trim().split(/\s+as\s+/)[0].trim();
      if (name && !name.startsWith("type")) names.add(name);
    }
  }
}
// Used by the Rust port beyond the web imports.
for (const extra of ["Square", "Maximize", "Copy"]) names.add(extra);

const FILLED = new Set(["Play", "Pause", "SkipBack", "SkipForward", "Heart"]);

const kebab = (n) =>
  n
    .replace(/([a-z])([A-Z0-9])/g, "$1-$2")
    .replace(/([0-9])([A-Z])/g, "$1-$2")
    .toLowerCase();
const screaming = (n) => kebab(n).replace(/-/g, "_").toUpperCase();

const STROKE =
  ' stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"';

function element(tag, attrs, filled) {
  let a = { ...attrs };
  delete a.key;
  if (tag === "polyline" || tag === "polygon") {
    const pts = a.points.trim().split(/[\s,]+/).map(Number);
    let d = "";
    for (let i = 0; i < pts.length; i += 2) d += `${i ? "L" : "M"}${pts[i]} ${pts[i + 1]}`;
    if (tag === "polygon") d += "Z";
    a = { d };
    tag = "path";
  }
  const attrText = Object.entries(a)
    .map(([k, v]) => ` ${k}="${v}"`)
    .join("");
  const fill = filled ? ' fill="currentColor"' : ' fill="none"';
  return `<${tag}${attrText}${STROKE}${fill}/>`;
}

let out = `//! Lucide icons (ISC licence, lucide-react ${JSON.parse(fs.readFileSync(path.join(lucide, "package.json"), "utf8")).version}).
//! Generated by \`tools/gen-icons.mjs\`; do not edit by hand.
#![allow(dead_code)]

use rune::Icon;

`;
const sorted = [...names].sort();
for (const name of sorted) {
  const file = path.join(lucide, "dist/esm/icons", `${kebab(name)}.mjs`);
  if (!fs.existsSync(file)) {
    console.error(`missing icon ${name} (${file})`);
    process.exitCode = 1;
    continue;
  }
  // Read the data literal rather than importing the module, which pulls in React.
  let src = fs.readFileSync(file, "utf8");
  // Aliases re-export their target: `export { default } from './x.mjs'`.
  for (let alias; (alias = src.match(/export \{ default \} from '\.\/([^']+)'/)); ) {
    src = fs.readFileSync(path.join(path.dirname(file), alias[1]), "utf8");
  }
  const literal = src.match(/const __iconData = (\{[\s\S]*?\n\});/);
  if (!literal) throw new Error(`no icon data in ${file}`);
  const data = new Function(`return (${literal[1]});`)();
  const emit = (suffix, filled) => {
    const body = data.node.map(([tag, attrs]) => element(tag, attrs, filled)).join("");
    out += `pub const ${screaming(name)}${suffix}: Icon = Icon { name: "${data.name}${suffix ? "-filled" : ""}", view: ${data.size ?? 24}.0, body: r#"${body}"# };\n`;
  };
  emit("", false);
  if (FILLED.has(name)) emit("_FILLED", true);
}
fs.writeFileSync(path.join(here, "../src/ui/icons.rs"), out);
console.log(`${sorted.length} icons`);
